"""Single-call "E2E-plan" baseline (ablation control).

Follows the end-to-end baseline design of Huot et al., "Agents' Room: Narrative
Generation through Multi-step Collaboration" (ICLR 2025): the whole artefact is
produced in ONE LLM call, but the model receives the same detailed instructions
that the specialised agents receive. Here that means:

  * the verbatim system prompts of OutlineAgent, CharacterAgent, ClueAgent and
    DeductionAgent (captured from the agent code itself, not rewritten by hand),
    with case-specific suspect IDs generalised because the culprit is not known
    before the single call;
  * the same setting guidance and mystery mechanic for the theme;
  * the full JSON Schema of CaseDossier generated by Pydantic.

No Henssge post-processing and no patch repair are applied, so the result
measures what a single call achieves when it is given the same information.
"""

from __future__ import annotations

import json
import re
from typing import Dict, Tuple

from agents import (
    CharacterAgent,
    ClueAgent,
    DeductionAgent,
    OutlineAgent,
    _get_mystery_style_mechanic,
    _get_setting_guidance,
)
from models import CaseDossier


class _PromptCaptured(Exception):
    """Raised by the recording stub to stop an agent right after it builds its prompt."""


# Case-specific IDs that appear in the agent prompts once a culprit is known.
# The single-call baseline must pick the culprit itself, so they are generalised.
_GENERALISE = [
    (r"For SUSP-01 \(Culprit\)", "For the culprit (the suspect whose id equals ground_truth.culprit_id)"),
    (r"The suspect with id 'SUSP-01' MUST have is_culprit = True \(matches GroundTruth\)",
     "The suspect whose id equals ground_truth.culprit_id MUST have is_culprit = True"),
    (r"SUSP-01's alibi statement", "The culprit's alibi statement"),
    (r"innocent suspect SUSP-02\): An incriminating piece of evidence pointing to SUSP-02's",
     "the first innocent suspect): An incriminating piece of evidence pointing to that suspect's"),
    (r"innocent suspect SUSP-03\): Suspicious physical trace of SUSP-03",
     "the second innocent suspect): Suspicious physical trace of that suspect"),
    (r"the culprit SUSP-01's claimed activity", "the culprit's claimed activity"),
]


async def _capture_system_prompts(theme: str) -> Dict[str, str]:
    """Run each agent's prompt construction against the bundled sample case and record its system prompt."""
    from llm_service import CaseGeneratorService

    sample = CaseGeneratorService.get_sample_case()
    captured: Dict[str, str] = {}

    def recorder(name: str):
        async def _stub(system_prompt: str, user_prompt: str):
            captured[name] = system_prompt
            raise _PromptCaptured()
        return _stub

    calls = [
        ("OutlineAgent", OutlineAgent, lambda a: a.generate(theme)),
        ("CharacterAgent", CharacterAgent, lambda a: a.generate(sample.victim, sample.ground_truth, theme)),
        ("ClueAgent", ClueAgent, lambda a: a.generate(sample.victim, sample.suspects, sample.ground_truth, theme)),
        ("DeductionAgent", DeductionAgent,
         lambda a: a.generate(sample.victim, sample.suspects, sample.evidences, sample.ground_truth, theme)),
    ]
    for name, cls, call in calls:
        agent = cls(client=None, model="prompt-capture")
        agent._call_llm_json = recorder(name)  # instance-level stub, class untouched
        try:
            await call(agent)
        except _PromptCaptured:
            pass
    return captured


def _generalise(text: str) -> str:
    for pattern, replacement in _GENERALISE:
        text = re.sub(pattern, replacement, text)
    return text


async def build_e2e_plan_prompts(theme: str) -> Tuple[str, str]:
    """Return (system_prompt, user_prompt) for the single-call E2E-plan baseline."""
    agent_prompts = await _capture_system_prompts(theme)
    sections = [
        "You are an End-to-End Mystery Case Generator. Produce the COMPLETE case dossier in ONE JSON object. "
        "Follow ALL of the specialist instructions below, in order, exactly as if you were each specialist in turn.",
    ]
    for name in ("OutlineAgent", "CharacterAgent", "ClueAgent", "DeductionAgent"):
        sections.append(f"### Instructions of {name}\n{_generalise(agent_prompts[name])}")
    system_prompt = "\n\n".join(sections)

    schema = json.dumps(CaseDossier.model_json_schema(), ensure_ascii=False)
    user_prompt = (
        f"Theme: {theme}\n"
        f"Setting Guidelines:\n{_get_setting_guidance(theme)}\n\n"
        f"Mystery Deduction Mechanic:\n{_get_mystery_style_mechanic(theme)}\n\n"
        "Output ONE JSON object that validates against this JSON Schema (field names and types must match exactly; "
        "times use HH:MM):\n"
        f"{schema}"
    )
    return system_prompt, user_prompt
